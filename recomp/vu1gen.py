#!/usr/bin/env python3
"""VU1 ahead-of-time translator: the game's 19 VU1 microprograms (one block of VIF1 DMA packages in .data,
0x3a1b80-0x3ac7b0; docs/hardware.md 1.1) -> gen/vu1_aot_NN.c (one per program) and gen/vu1_aot_tab.c.

Version 2 (whole programs, timing at build time): vu1timing.py explores every path of a program from its entries
(0, and the pc each run ends at, i.e. the MSCNT entries) under the interpreters' timing model and proves, for every
consumer of Q (MULq, ADDq, ...) and P (MFP), whether the latest DIV/SQRT/RSQRT or EFU result has arrived. The
program then becomes one C function with one label per node (pc; pc in a taken branch's delay slot; pc after an
E-bit), straight-line code per pair through pair_untimed() (vu1_core.h: the interpreter's own upper()/lower() on
constant instruction words, so decode folds away and the semantics stay the interpreter's) and goto for control
flow. No cycles are counted: a SAFE consumer commits the pending Q/P (q_commit/p_commit) just before it reads, an
OLD consumer reads the previous value, and the VI register a branch must read old (written by the previous pair) is
a constant. A run entering anywhere else returns to the interpreter at once (exact: the run has not started).
A program the proof does not cover completely (an AMBIGUOUS consumer, a JR/JALR, a path leaving the program, a
branch whose previous pair is not static) is emitted the version 1 way instead: every pair is the interpreter's
step() with the cycle model, cut into functions of 64 pairs.
The output is derived from the game: never commit it.
usage: vu1gen.py [OUTDIR]   (default gen; run from this directory, or called by bulk2.py)"""
import sys, os, struct, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import r5900 as R
HERE = os.path.dirname(os.path.abspath(__file__))

def programs(exe):
    blob = R.load(exe)
    def w(va): return struct.unpack_from('<I', blob, va - 0x100000)[0]
    # DMA packages: a CNT tag (BASE/OFFSET vifcodes), then a RET tag whose two vifcodes and qwc qwords hold the MPGs
    progs = []; va = 0x3a1b80
    while va < 0x3ac7b0:
        qwc = w(va) & 0xFFFF
        stream = [w(va + 8), w(va + 12)] + [w(va + 16 + 4 * i) for i in range(qwc * 4)]
        img = {}; i = 0
        while i < len(stream):
            c = stream[i]; cmd = (c >> 24) & 0x7F; i += 1
            if cmd == 0x4A:                                    # MPG: num pairs (0 = 256) to instruction address imm
                num = ((c >> 16) & 0xFF) or 256
                for k in range(num): img[(c & 0xFFFF) + k] = (stream[i + 2 * k], stream[i + 2 * k + 1])
                i += 2 * num
            elif cmd in (0x00, 0x02, 0x03): pass               # NOP, OFFSET, BASE
            else: break                                        # past the last package
        if img:
            assert sorted(img) == list(range(len(img))), 'program not contiguous from 0'
            progs.append([img[k] for k in range(len(img))])
        va += 16 + qwc * 16
    assert len(progs) == 19, len(progs)
    return progs

BANNER = '/* Generated by vu1gen.py from SLUS_210.75. Derived from the game: never commit. */'

def v2_plan(code, R):
    """what version 2 needs from the analysis: the pcs whose Q/P consumer commits first, and per branch node the VI
    register written by the previous pair (-1 none); None if the proof does not cover the program"""
    import vu1timing as T
    if R.dynamic or R.leaves: return None
    cls = [T.classify(o) for o in list(R.qobs.values()) + list(R.pobs.values())]
    if 'AMBIGUOUS' in cls: return None
    qc = {pc for pc, o in R.qobs.items() if T.classify(o) == 'SAFE'}
    pcc = {pc for pc, o in R.pobs.items() if T.classify(o) == 'SAFE'}
    prev = {}
    for node, pvs in R.prev_vi.items():
        d = R.dec[node[0]]
        if not d.bvi: continue
        k = {v if v in d.bvi else -1 for v in pvs}
        if len(k) != 1: return None
        prev[node] = k.pop()
    return qc, pcc, prev

def emit_v2(p, code, R, plan):
    qc, pcc, prev = plan
    def lab(node):
        pc, bp, eb = node
        return 'N%d%s%s' % (pc, '' if bp < 0 else '_b%d' % bp, '_e' if eb else '')
    L = [BANNER, '#define VU1_FLAG_DELAY 0   /* compiled programs are used with HG_VUFLAGDELAY=0 only */', '#include "vu1_core.h"',
         '/* one instruction pair at k: pre = the Q/P commit of a SAFE consumer; prev = VI register written by the previous pair */',
         '#define PAIR(k, lo, up, pre, prev) do { Dec d_ = {0}; dec_const(&d_, lo, up); pre; taken = pair_untimed(&d_, (k), (prev), &pvo, &tgt); } while (0)',
         '/* the run ends after this pair (the pair after an E-bit pair): Q and P committed, as the interpreter does */',
         '#define END(next) do { vu1_tpc = (next); q_commit(); p_commit(); n_insns += (uint64_t)(n - s->n); s->n = n; return 1; } while (0)',
         '/* a runaway program (no end after VU1_MAXN pairs) goes back to the interpreter, which reports it */',
         '#define LOOP(target, eb) do { if (__builtin_expect(n >= VU1_MAXN, 0)) { n_insns += (uint64_t)(n - s->n); s->n = n; s->pc = (target); \\',
         '    s->branch_pending = 0; s->ebit_pending = (eb); s->prev_vi = -1; s->prev_old = pvo; return 0; } } while (0)',
         f'int aot_run_{p:02d}(RunSt *s) {{',
         '    if (q_wait || p_wait) return 0;   /* a Q/P pending from an unfinished run: the interpreter counts it down */',
         '    long n = s->n; uint16_t pvo = 0; uint32_t tgt = 0; int taken = 0;',
         '    switch (s->pc) { ' + ' '.join(f'case {e}: goto {lab((e, -1, 0))};' for e in sorted(R.entries)) + ' default: return 0; }']
    for node in sorted(R.nodes):
        pc, bp, eb = node; d = R.dec[pc]; lo, up = code[pc]
        pre = ' '.join((['q_commit();'] if pc in qc else []) + (['p_commit();'] if pc in pcc else [])) or '(void)0'
        L.append(f'{lab(node)}: n++; PAIR({pc}, 0x{lo:08x}u, 0x{up:08x}u, {pre}, {prev.get(node, -1)});')
        nxt = bp if bp >= 0 else (pc + 1) & 2047
        succ = R.nodes[node]
        if eb:
            assert succ == {('end', nxt)}; L.append(f'    END({nxt});'); continue
        if 0 <= bp <= pc: L.append(f'    LOOP({bp}, {d.ebit});')
        tk = [x for x in succ if x[1] >= 0]; nt = [x for x in succ if x[1] < 0]
        assert len(tk) <= 1 and len(nt) <= 1 and tk + nt, (node, succ)
        if tk and nt: L.append(f'    if (taken) goto {lab(tk[0])};')
        L.append(f'    goto {lab((nt or tk)[0])};')
    L.append('}')
    return L

def generate(outdir, game=None):
    import vu1timing as T
    game = game or os.environ.get('HG_GAME_DIR', os.path.join(HERE, '..', 'game'))
    progs = programs(os.path.join(game, 'SLUS_210.75'))
    os.makedirs(outdir, exist_ok=True)
    for f in glob.glob(os.path.join(outdir, 'vu1_aot_*.c')): os.remove(f)
    banner = BANNER
    CH = 64   # instruction pairs per C function: compile time grows faster than linearly with function size
    v1 = []
    for p, code in enumerate(progs):
        R = T.analyse(code, T.program_entries(p, ()))
        plan = v2_plan(code, R)
        if plan:
            open(os.path.join(outdir, f'vu1_aot_{p:02d}.c'), 'w').write('\n'.join(emit_v2(p, code, R, plan)) + '\n')
            continue
        v1.append(p)
        n = len(code); chunks = [(c, min(c + CH, n)) for c in range(0, n, CH)]
        L = [banner, '#include "vu1_core.h"',
             '/* one pair; leaves the chunk through "dispatch" when the next pc is not the next label */',
             '#define AOT_STEP(k, lo, up) do { \\',
             '    if (__builtin_expect(S.n >= VU1_MAXN, 0)) { *s0 = S; return 0; }   /* the interpreter reports a runaway */ \\',
             '    Dec d_ = {0}; dec_const(&d_, lo, up); \\',
             '    if (step(&d_, &S, (k), 1)) { *s0 = S; return 1; } \\',
             '    S.n++; \\',
             '    if (__builtin_expect(S.pc != (k) + 1, 0)) goto dispatch; \\',
             '} while (0)']
        for a, b in chunks:   # returns 1: program ended, 0: hand over to the interpreter, 2: pc left this chunk
            L += [f'static int chunk_{a}(RunSt *s0) {{', '    RunSt S = *s0;', 'dispatch:',
                  '    switch (S.pc) { ' + ' '.join(f'case {k}: goto L{k};' for k in range(a, b)) + ' default: *s0 = S; return 2; }']
            L += [f'L{k}: AOT_STEP({k}, 0x{lo:08x}u, 0x{up:08x}u);' for k, (lo, up) in enumerate(code[a:b], a)]
            L += ['    goto dispatch;', '}']
        L += [f'int aot_run_{p:02d}(RunSt *s) {{', '    for (;;) {', '        int r;',
              '        switch (s->pc / %d) { ' % CH + ' '.join(f'case {a // CH}: r = chunk_{a}(s); break;' for a, b in chunks) + ' default: return 0; }',
              '        if (r != 2) return r;', '        if (s->pc >= %d) return 0;' % n, '    }', '}']
        open(os.path.join(outdir, f'vu1_aot_{p:02d}.c'), 'w').write('\n'.join(L) + '\n')
    T = [banner, '#include "vu1_core.h"']
    for p, code in enumerate(progs):
        T.append(f'int aot_run_{p:02d}(RunSt *s0);')
        T.append(f'static const uint32_t code_{p:02d}[{2 * len(code)}] = {{')
        T += ['    ' + ' '.join(f'0x{lo:08x}u, 0x{up:08x}u,' for lo, up in code[k:k + 4]) for k in range(0, len(code), 4)]
        T.append('};')
    T.append(f'const int aot_nprogs = {len(progs)};')
    T.append('const AotProg aot_progs[] = {')
    T += [f'    {{ code_{p:02d}, {len(code)}, aot_run_{p:02d} }},' for p, code in enumerate(progs)]
    T.append('};')
    open(os.path.join(outdir, 'vu1_aot_tab.c'), 'w').write('\n'.join(T) + '\n')
    return f'{len(progs)} VU1 programs, {sum(map(len, progs))} instruction pairs -> {outdir} ({len(progs) - len(v1)} whole programs with timing proven at build time' + (f'; per pair with the cycle model: {v1})' if v1 else ')')

if __name__ == '__main__':
    print(generate(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'gen')))
